# Database operations for accounts, profiles, and user logs.

import hashlib
import json
import math
import os
import sqlite3
from contextlib import contextmanager

import psycopg
from streamlit import secrets
from streamlit.errors import StreamlitSecretNotFoundError

# An explicit SQLite path supports isolated database tests.
DB_PATH = None
IntegrityError = (sqlite3.IntegrityError, psycopg.IntegrityError)


class DatabaseConfigurationError(RuntimeError):
    pass


def get_database_url():
    url = os.environ.get("DATABASE_URL")
    if not url:
        try:
            url = secrets.get("DATABASE_URL")
        except StreamlitSecretNotFoundError:
            pass
    if not url:
        raise DatabaseConfigurationError(
            "Set DATABASE_URL in the environment or .streamlit/secrets.toml."
        )
    return url


class PostgresConnection(psycopg.Connection):
    def execute(self, query, params=None):
        # The shared SQL uses SQLite-style placeholders for the isolated tests.
        return super().execute(query.replace("?", "%s"), params)


@contextmanager
def get_connection():
    if DB_PATH is None:
        with PostgresConnection.connect(
            get_database_url(), sslmode="require", connect_timeout=10
        ) as connection:
            connection.execute("SET LOCAL search_path TO sustain, pg_catalog")
            yield connection
        return

    connection = sqlite3.connect(DB_PATH)
    try:
        yield connection
        connection.commit()
    except Exception:
        connection.rollback()
        raise
    finally:
        connection.close()


def init_db():
    identity = "INTEGER PRIMARY KEY AUTOINCREMENT"
    user_id_type = "INTEGER"
    weight_type = "REAL"
    with get_connection() as conn:
        if DB_PATH is None:
            conn.execute("SELECT pg_advisory_xact_lock(710528649)")
            conn.execute("CREATE SCHEMA IF NOT EXISTS sustain")
            identity = "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
            user_id_type = "BIGINT"
            weight_type = "DOUBLE PRECISION"
        conn.execute(
            f"""
            CREATE TABLE IF NOT EXISTS users (
                id {identity},
                username TEXT UNIQUE NOT NULL,
                password_hash TEXT NOT NULL,
                salt TEXT NOT NULL,
                onboarding_complete INTEGER NOT NULL DEFAULT 0
            )
            """
        )
        conn.execute(
            f"""
            CREATE TABLE IF NOT EXISTS profiles (
                user_id {user_id_type} PRIMARY KEY REFERENCES users(id),
                profile_json TEXT,
                targets_json TEXT,
                targets_manual INTEGER NOT NULL DEFAULT 0
            )
            """
        )
        # There is one row for each food the user logs into a meal slot on a given day.
        conn.execute(
            f"""
            CREATE TABLE IF NOT EXISTS food_log (
                id {identity},
                user_id {user_id_type} NOT NULL REFERENCES users(id),
                log_date TEXT NOT NULL,
                meal_slot TEXT NOT NULL,
                food_name TEXT NOT NULL,
                calories INTEGER NOT NULL,
                protein_g INTEGER NOT NULL,
                carbs_g INTEGER NOT NULL,
                fat_g INTEGER NOT NULL
            )
            """
        )
        if DB_PATH is None:
            columns = conn.execute(
                "SELECT column_name FROM information_schema.columns "
                "WHERE table_schema = 'sustain' AND table_name = 'food_log'"
            ).fetchall()
        else:
            columns = [(row[1],) for row in conn.execute("PRAGMA table_info(food_log)")]
        existing = {column for (column,) in columns}
        for column, definition in (
            ("quantity", "DOUBLE PRECISION NOT NULL DEFAULT 1 CHECK (quantity > 0)"),
            ("base_quantity", "DOUBLE PRECISION NOT NULL DEFAULT 1 CHECK (base_quantity > 0)"),
            ("quantity_unit", "TEXT NOT NULL DEFAULT 'servings'"),
        ):
            if column not in existing:
                conn.execute(f"ALTER TABLE food_log ADD COLUMN {column} {definition}")
        conn.execute(
            f"""
            CREATE TABLE IF NOT EXISTS weight_log (
                id {identity},
                user_id {user_id_type} NOT NULL REFERENCES users(id),
                log_date TEXT NOT NULL,
                weight_kg {weight_type} NOT NULL,
                note TEXT NOT NULL DEFAULT '',
                UNIQUE(user_id, log_date)
            )
            """
        )
        conn.execute(
            f"""
            CREATE TABLE IF NOT EXISTS saved_recipes (
                id {identity},
                user_id {user_id_type} NOT NULL REFERENCES users(id),
                recipe_id TEXT NOT NULL,
                recipe_json TEXT NOT NULL,
                UNIQUE(user_id, recipe_id)
            )
            """
        )


def hash_password(password, salt):
    # We never store the real password. We store a scrambled version (a hash).
    # The salt is random text mixed in, so two people with the same password
    # still get different hashes.
    return hashlib.pbkdf2_hmac(
        "sha256", password.encode(), bytes.fromhex(salt), 100_000
    ).hex()


# ---- Sign up and log in ----

def create_user(username, password):
    """Sign up. Returns True if it worked, False if the username is taken."""
    salt = os.urandom(16).hex()
    try:
        with get_connection() as conn:
            conn.execute(
                "INSERT INTO users (username, password_hash, salt) VALUES (?, ?, ?)",
                (username, hash_password(password, salt), salt),
            )
        return True
    except IntegrityError:  # UNIQUE rule broken: username already exists
        return False


def check_login(username, password):
    """Log in. Returns the user as a dict if the password is right, else None."""
    with get_connection() as conn:
        row = conn.execute(
            "SELECT id, username, password_hash, salt, onboarding_complete "
            "FROM users WHERE username = ?",
            (username,),
        ).fetchone()
    if row is None:
        return None  # no such user
    user_id, name, stored_hash, salt, onboarding_complete = row
    if hash_password(password, salt) != stored_hash:
        return None  # wrong password
    return {"id": user_id, "username": name, "onboarding_complete": bool(onboarding_complete)}


def mark_onboarding_complete(user_id):
    # Kian's questionnaire calls this when the user submits it.
    with get_connection() as conn:
        conn.execute("UPDATE users SET onboarding_complete = 1 WHERE id = ?", (user_id,))


# ---- Password change ----

def change_password(user_id, current_password, new_password):
    """Logged-in password change. Returns True if the current password was right."""
    with get_connection() as conn:
        row = conn.execute(
            "SELECT password_hash, salt FROM users WHERE id = ?", (user_id,)
        ).fetchone()
        if row is None or hash_password(current_password, row[1]) != row[0]:
            return False
        salt = os.urandom(16).hex()
        conn.execute(
            "UPDATE users SET password_hash = ?, salt = ? WHERE id = ?",
            (hash_password(new_password, salt), salt, user_id),
        )
    return True


# ---- Profile and targets (SCRUM-89, 94, 95) ----

def save_profile(user_id, profile, *, complete_onboarding=False):
    """Save the questionnaire answers as a dict (e.g. dataclasses.asdict(user_profile))."""
    with get_connection() as conn:
        conn.execute(
            "INSERT INTO profiles (user_id, profile_json) VALUES (?, ?) "
            "ON CONFLICT(user_id) DO UPDATE SET profile_json = excluded.profile_json",
            (user_id, json.dumps(profile)),
        )
        if complete_onboarding:
            conn.execute("UPDATE users SET onboarding_complete = 1 WHERE id = ?", (user_id,))


def get_profile(user_id):
    """The saved profile dict, or None if the questionnaire hasn't been saved yet."""
    with get_connection() as conn:
        row = conn.execute(
            "SELECT profile_json FROM profiles WHERE user_id = ?", (user_id,)
        ).fetchone()
    return json.loads(row[0]) if row and row[0] else None


def save_targets(user_id, targets, manual=False):
    """Save daily targets: {"calories", "protein_g", "carbs_g", "fat_g"}.
    manual=True means the user set them by hand, so automatic recalculation leaves them alone."""
    with get_connection() as conn:
        conn.execute(
            "INSERT INTO profiles (user_id, targets_json, targets_manual) VALUES (?, ?, ?) "
            "ON CONFLICT(user_id) DO UPDATE SET targets_json = excluded.targets_json, "
            "targets_manual = excluded.targets_manual",
            (user_id, json.dumps(targets), int(manual)),
        )


def get_targets(user_id):
    """Returns (targets dict or None, manual flag)."""
    with get_connection() as conn:
        row = conn.execute(
            "SELECT targets_json, targets_manual FROM profiles WHERE user_id = ?", (user_id,)
        ).fetchone()
    if not row or not row[0]:
        return None, False
    return json.loads(row[0]), bool(row[1])



# Food diary
FOOD_NUTRIENTS = ("calories", "protein_g", "carbs_g", "fat_g")


def _food_entry(row, fields):
    entry = dict(zip(fields + FOOD_NUTRIENTS + ("quantity", "base_quantity", "quantity_unit"), row))
    scale = entry["quantity"] / entry.pop("base_quantity")
    for nutrient in FOOD_NUTRIENTS:
        entry[nutrient] = round(entry[nutrient] * scale)
    return entry


def get_food_entries(user_id, log_date):
    """Food logged on the supplied ISO date, with nutrition scaled to the logged quantity."""
    with get_connection() as conn:
        rows = conn.execute(
            "SELECT id, meal_slot, food_name, calories, protein_g, carbs_g, fat_g, "
            "quantity, base_quantity, quantity_unit FROM food_log "
            "WHERE user_id = ? AND log_date = ? ORDER BY id",
            (user_id, log_date),
        ).fetchall()
    return [_food_entry(row, ("id", "meal_slot", "food_name")) for row in rows]


def _validate_food_quantity(quantity):
    if not math.isfinite(quantity) or quantity <= 0:
        raise ValueError("Quantity must be a positive number.")


def add_food_entry(
    user_id, log_date, meal_slot, food_name, calories, protein_g, carbs_g, fat_g,
    *, quantity=1.0, quantity_unit="servings",
):
    """Log a food with nutrition totals for its starting quantity."""
    _validate_food_quantity(quantity)
    with get_connection() as conn:
        conn.execute(
            "INSERT INTO food_log (user_id, log_date, meal_slot, food_name, "
            "calories, protein_g, carbs_g, fat_g, quantity, base_quantity, quantity_unit) "
            "VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)",
            (user_id, log_date, meal_slot, food_name, calories, protein_g, carbs_g, fat_g,
             quantity, quantity, quantity_unit),
        )


def update_food_quantity(user_id, log_date, entry_id, quantity, *, meal_slot=None):
    _validate_food_quantity(quantity)
    with get_connection() as conn:
        conn.execute(
            "UPDATE food_log SET quantity = ?, meal_slot = COALESCE(?, meal_slot) "
            "WHERE user_id = ? AND log_date = ? AND id = ?",
            (quantity, meal_slot, user_id, log_date, entry_id),
        )


def delete_food_entry(user_id, log_date, entry_id):
    with get_connection() as conn:
        conn.execute(
            "DELETE FROM food_log WHERE user_id = ? AND log_date = ? AND id = ?",
            (user_id, log_date, entry_id),
        )


# Weight log: one weigh-in per user per day, always stored in kg.
def get_weight_entries(user_id):
    """All of a user's weigh-ins, oldest first, as a list of dicts."""
    with get_connection() as conn:
        rows = conn.execute(
            "SELECT id, log_date, weight_kg, note FROM weight_log "
            "WHERE user_id = ? ORDER BY log_date",
            (user_id,),
        ).fetchall()
    keys = ["id", "log_date", "weight_kg", "note"]
    return [dict(zip(keys, row)) for row in rows]


def save_weight_entry(user_id, log_date, weight_kg, note=""):
    """Add a weigh-in, or replace the one already logged for that date."""
    with get_connection() as conn:
        conn.execute(
            "INSERT INTO weight_log (user_id, log_date, weight_kg, note) "
            "VALUES (?, ?, ?, ?) ON CONFLICT(user_id, log_date) "
            "DO UPDATE SET weight_kg = excluded.weight_kg, note = excluded.note",
            (user_id, log_date, weight_kg, note),
        )
        latest = conn.execute(
            "SELECT weight_kg FROM weight_log "
            "WHERE user_id = ? ORDER BY log_date DESC LIMIT 1",
            (user_id,),
        ).fetchone()
        if latest:
            _update_profile_weight(conn, user_id, float(latest[0]))


def delete_weight_entry(user_id, entry_id):
    with get_connection() as conn:
        conn.execute(
            "DELETE FROM weight_log WHERE user_id = ? AND id = ?",
            (user_id, entry_id),
        )
        latest = conn.execute(
            "SELECT weight_kg FROM weight_log "
            "WHERE user_id = ? ORDER BY log_date DESC LIMIT 1",
            (user_id,),
        ).fetchone()
        if latest:
            _update_profile_weight(conn, user_id, float(latest[0]))


def update_weight_entry(user_id, entry_id, log_date, weight_kg, note=""):
    """Update an existing weigh-in and keep profile weight aligned with the latest log."""
    with get_connection() as conn:
        conn.execute(
            "UPDATE weight_log SET log_date = ?, weight_kg = ?, note = ? "
            "WHERE user_id = ? AND id = ?",
            (log_date, weight_kg, note, user_id, entry_id),
        )
        latest = conn.execute(
            "SELECT weight_kg FROM weight_log "
            "WHERE user_id = ? ORDER BY log_date DESC LIMIT 1",
            (user_id,),
        ).fetchone()
        if latest:
            _update_profile_weight(conn, user_id, float(latest[0]))


def _update_profile_weight(conn, user_id, weight_kg):
    """Keep the saved profile weight aligned with the latest weigh-in."""
    row = conn.execute(
        "SELECT profile_json FROM profiles WHERE user_id = ?", (user_id,)
    ).fetchone()
    if not row or not row[0]:
        return
    profile = json.loads(row[0])
    profile["weight_kg"] = round(weight_kg, 2)
    conn.execute(
        "UPDATE profiles SET profile_json = ? WHERE user_id = ?",
        (json.dumps(profile), user_id),
    )


def get_logged_foods(user_id, limit=30, *, at_base_quantity=False):
    """Distinct foods, newest first, with optional unscaled nutrition."""
    with get_connection() as conn:
        rows = conn.execute(
            "SELECT food_name, calories, protein_g, carbs_g, fat_g, "
            "quantity, base_quantity, quantity_unit FROM food_log "
            "WHERE id IN (SELECT MAX(id) FROM food_log WHERE user_id = ? GROUP BY food_name) "
            "ORDER BY id DESC LIMIT ?",
            (user_id, limit),
        ).fetchall()
    if at_base_quantity:
        fields = ("food_name",) + FOOD_NUTRIENTS + ("quantity", "base_quantity", "quantity_unit")
        return [dict(zip(fields, row)) for row in rows]
    return [_food_entry(row, ("food_name",)) for row in rows]


def get_saved_recipes(user_id):
    """Return a user's saved recipe data in the order it was saved."""
    with get_connection() as conn:
        rows = conn.execute(
            "SELECT recipe_id, recipe_json FROM saved_recipes "
            "WHERE user_id = ? ORDER BY id",
            (user_id,),
        ).fetchall()
    return [
        {**json.loads(recipe_json), "recipe_id": recipe_id}
        for recipe_id, recipe_json in rows
    ]


def save_recipe(user_id, recipe_id, recipe):
    """Save or refresh a recipe for one user."""
    with get_connection() as conn:
        conn.execute(
            "INSERT INTO saved_recipes (user_id, recipe_id, recipe_json) "
            "VALUES (?, ?, ?) ON CONFLICT(user_id, recipe_id) "
            "DO UPDATE SET recipe_json = excluded.recipe_json",
            (user_id, str(recipe_id), json.dumps(recipe)),
        )


def remove_saved_recipe(user_id, recipe_id):
    """Remove a saved recipe without affecting other users' copies."""
    with get_connection() as conn:
        conn.execute(
            "DELETE FROM saved_recipes WHERE user_id = ? AND recipe_id = ?",
            (user_id, str(recipe_id)),
        )
